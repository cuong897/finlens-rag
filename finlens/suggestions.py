def clean(text):
    return " ".join(tokens(text))


def number_format(words):
    # A single 1,234 is ambiguous. Learn grouping only from values containing
    # at least two identical thousands separators on this page.
    separators = set()
    for word in words:
        raw = word[4].strip("()-−")
        for separator in (",", "."):
            if re.fullmatch(r"\d{1,3}(?:" + re.escape(separator) + r"\d{3}){2,}", raw):
                separators.add(separator)
    return next(iter(separators)) if len(separators) == 1 else None


def parse_amount(raw, grouping=None):
    text = raw.strip().replace("−", "-")
    negative = text.startswith("(") and text.endswith(")")
    if negative:
        text = text[1:-1]
    for separator in (",", "."):
        if re.fullmatch(r"-?\d{1,3}(?:" + re.escape(separator) + r"\d{3}){2,}", text):
            grouping = separator
    if re.fullmatch(r"-?\d{1,24}", text):
        pass
    elif grouping and re.fullmatch(r"-?\d{1,3}(?:" + re.escape(grouping) + r"\d{3})+(?:" + (r"\." if grouping == "," else ",") + r"\d{1,8})?", text):
        text = text.replace(grouping, "").replace(",", ".")
    elif re.fullmatch(r"-?\d+[.,]\d{1,2}", text):
        text = text.replace(",", ".")
    else:
        return None
    if negative:
        if text.startswith("-"):
            return None
        text = "-" + text
    if not re.fullmatch(r"-?\d{1,24}(?:\.\d{1,8})?", text):
        return None
    return format(Decimal(text), "f")


def rows_from_words(words):
    rows = []
    for word in sorted(words, key=lambda w: ((w[1] + w[3]) / 2, w[0])):
        center = (word[1] + word[3]) / 2
        tolerance = max(2, (word[3] - word[1]) * 0.3)
        if rows and abs(center - rows[-1]["y"]) <= tolerance:
            rows[-1]["words"].append(word)
        else:
            rows.append({"y": center, "words": [word]})
    for row in rows:
        row["words"].sort(key=lambda w: w[0])
    return rows


def currency_unit(rows, header, height):
    nearby = [row for row in rows if header["y"] - 6 * height <= row["y"] <= header["y"] + 2 * height]
    lines = [clean(" ".join(word[4] for word in row["words"])) for row in nearby]
    text = " ".join(lines)
    currencies = {code for code in ("VND", "USD", "EUR") if code.lower() in text.split()}
    if re.search(r"\b(?:don vi(?: tinh)?|unit)\b.*\bdong\b", text):
        currencies.add("VND")
    # "ty" in "Cong ty" is a company label, not "ty dong". A scale must
    # occur in a unit declaration or directly next to a currency marker.
    declarations = [line for line in lines if re.search(r"\b(?:don vi(?: tinh)?|units?|currency)\b", line)
                    or re.search(r"\b(?:billion|billions|million|millions|thousand|thousands|ty|trieu|nghin|ngan) (?:vnd|usd|eur|dong)\b|\b(?:vnd|usd|eur|dong|in) (?:billion|billions|million|millions|thousand|thousands|ty|trieu|nghin|ngan)\b", line)]
    if any(re.search(r"\d", line) for line in declarations):
        return None
    allowed = set("tinh of in vnd usd eur dong viet nam vietnam vietnamese dollar dollars euro euros one billion billions million millions thousand thousands ty trieu nghin ngan".split())
    for line in declarations:
        declared = re.split(r"\b(?:don vi(?: tinh)?|units?|currency)\b", line, maxsplit=1)
        if len(declared) == 2 and (not declared[1].strip() or set(declared[1].split()) - allowed):
            return None
    unit_text = " ".join(declarations)
    scales = {unit for unit, pattern in [("billion", r"\b(?:billion|billions|ty)\b"),
                                        ("million", r"\b(?:million|millions|trieu)\b"),
                                        ("thousand", r"\b(?:thousand|thousands|nghin|ngan)\b")]
              if re.search(pattern, unit_text)}
    if len(currencies) != 1 or len(scales) > 1:
        return None
    return next(iter(currencies)), next(iter(scales)) if scales else "one"


def unit_mentioned(rows, header, height):
    """An explicit but unsupported/ambiguous declaration must block inheritance."""
    for row in rows:
        if not header['y']-6*height<=row['y']<=header['y']+2*height:continue
        text=' '.join(w[4] for w in row['words'])
        if re.search(r'\b(?:don vi|unit|units|currency)\b',clean(text)):return True
        if re.search(r'\b(?:VND|USD|EUR|JPY|GBP|CNY|AUD|SGD|HKD|CHF)\b',text,re.I):return True
        if re.fullmatch(r'[A-Z]{3}',text.strip()):return True
    return False


def identify_metric(label):
    normalized = clean(label)
    normalized = re.sub(r"\b\d+\b", "", normalized)
    normalized = " ".join(normalized.split())
    normalized = re.sub(r"^(?:[a-z]|i{1,3}|iv|v)\s+", "", normalized)
    normalized = re.sub(r"^(?:including|in which)\s+", "", normalized)
    matches = {metric for metric, labels in LABELS.items() if normalized in labels}
    return next(iter(matches)) if len(matches) == 1 else None


def period_columns(row, rows, context, height):
    """Resolve relative/date headings only against an explicit annual period."""
    try:
        start, end = date.fromisoformat(context["period_start"]), date.fromisoformat(context["period_end"])
        year = context["report_year"]
        if type(year) is not int or end.year not in {year, year + 1} or not 364 <= (end - start).days <= 366:
            return [], None
    except (KeyError, TypeError, ValueError):
        return [], None
    words = row["words"]
    dated = []
    for w in words:
        match = re.fullmatch(r"(\d{1,2})[/-](\d{1,2})[/-](\d{4})", w[4])
        if match:
            try:
                actual = date(*map(int, [match[3], match[2], match[1]]))
            except ValueError:
                continue
            if actual in {start, end}:
                dated.append((*w[:4], str(year if actual == end else year - 1), *w[5:]))
    if len(dated) == 2 and {w[4] for w in dated} == {str(year), str(year - 1)}:
        return dated, "period_date"
    months = "january february march april may june july august september october november december".split()
    above = clean(" ".join(w[4] for r in rows if row["y"] - height * 12 <= r["y"] < row["y"] for w in r["words"]))
    above += ' ' + context.get('_shared_page_caption','')
    endings = [f"{end.day} {months[end.month - 1]} {end.year}", f"{end.day:02d} {end.month:02d} {end.year}",
               f"{end.year} {end.month:02d} {end.day:02d}"]
    if not any(ending in above for ending in endings):
        return [], None
    relative = []
    names = {"current year": year, "ending balance": year, "closing balance": year,
             "previous year": year - 1, "prior year": year - 1, "beginning balance": year - 1, "opening balance": year - 1}
    for left, right in zip(words, words[1:]):
        label = clean(left[4] + " " + right[4])
        if label in names and right[0] - left[2] < height:
            relative.append((left[0], min(left[1], right[1]), right[2], max(left[3], right[3]), str(names[label]), *right[5:]))
    return (relative, "document_fiscal_period") if len(relative) == 2 and len({w[4] for w in relative}) == 2 else ([], None)


def page_regions(words, width, page_height):
    """Separate facing statements using titles or matching table declarations."""
    if width <= page_height * 1.2:
        return [(0, width)]
    # Report navigation can cross the center while two independent printed
    # statements sit below it. Recognize actual titles in the body heading band.
    band=[w for w in words if page_height*.08 <= (w[1]+w[3])/2 <= page_height*.25]
    titles=[clean(' '.join(w[4] for w in band if (w[0]>=width/2)==bool(half))) for half in [0,1]]
    financial=[bool(re.search(r'\b(?:balance sheet|income statement|statement of income|cash flow statement|statement of cash flows)\b',t)) for t in titles]
    auditor=[bool(re.search(r'\bindependent auditors? (?:report|s report)\b',t)) for t in titles]
    if all(financial) or (financial[0] and auditor[1]) or (financial[1] and auditor[0]):
        return [(0,width/2),(width/2,width)]
    # A continuation half may omit the title/date but repeat exactly the same
    # two relative column headings and explicit currency declaration.
    signatures=[]
    for half in [0,1]:
        half_rows=rows_from_words([w for w in words if (w[0]>=width/2)==bool(half)])
        height=statistics.median(w[3]-w[1] for r in half_rows for w in r['words']) if half_rows else 1
        found=set()
        for row in half_rows:
            if row['y']>page_height*.4 or not currency_unit(half_rows,row,height):continue
            text=clean(' '.join(w[4] for w in row['words']))
            for left,right in [('closing balance','opening balance'),('current year','prior year'),('current year','previous year')]:
                if left in text and right in text:found.add((left,right))
        signatures.append(found)
    if any(financial) and signatures[0]&signatures[1]:
        return [(0,width/2),(width/2,width)]
    if any(w[0] < width / 2 < w[2] for w in words):return [(0,width)]
    pairs = [[], []]
    height = statistics.median(w[3] - w[1] for w in words)
    for row in rows_from_words(words):
        if row["y"] > page_height * .4:
            continue
        for half in (0, 1):
            cols = [w for w in row["words"] if (w[0] >= width / 2) == bool(half)
                    and re.fullmatch(r"(?:19|20)\d{2}|\d{1,2}[/-]\d{1,2}[/-](?:19|20)\d{2}", w[4])]
            if len(cols) == 2 and len({w[4] for w in cols}) == 2 and all(
                any(clean(w[4]) in {"vnd", "usd", "eur"} and abs(w[2] - col[2]) < height
                    and 0 < (w[1] + w[3]) / 2 - row["y"] < height * 2 for w in words) for col in cols):
                pairs[half].append(tuple(w[4] for w in cols))
    return [(0, width / 2), (width / 2, width)] if set(pairs[0]) & set(pairs[1]) else [(0, width)]


def extract_page(page, document_id, page_number, *, context=None, ocr_dir=None):
    if page.rotation:
        return {"candidates": [], "warnings": ["Trang bị xoay; hãy nhập chỉ tiêu thủ công sau khi kiểm tra PDF."], "notice": NOTICE}
    ocr_warnings = []
    textpage = None
    if needs_ocr(page):
        textpage, notice = textpage_ocr(page, ocr_dir)
        ocr_warnings.append(notice)
    words = page.get_text("words", textpage=textpage) if textpage is not None else page.get_text("words")
    if len(words) > 12000:
        return {"candidates": [], "warnings": ocr_warnings + ["Trang có quá nhiều từ để ghép dòng an toàn; hãy đối chiếu và nhập thủ công."], "notice": NOTICE}
    if not words:
        return {"candidates": [], "warnings": ocr_warnings + ["Trang chưa có văn bản để đọc số liệu; có thể cần OCR."], "notice": NOTICE}
    candidates, warnings = [], ocr_warnings
    regions=page_regions(words,page.rect.width,page.rect.height)
    local_context=dict(context or {})
    if len(regions)>1:
        local_context['_shared_page_caption']=clean(' '.join(w[4] for w in words if w[3]<page.rect.height*.25))
    for start, end in regions:
        region = [(w[0] - start, w[1], w[2] - start, *w[3:]) for w in words if start <= w[0] and w[2] <= end]
        found, notes = extract_region(region, end - start, page.rect.height, document_id, page_number, local_context)
        for candidate in found:
            if textpage is not None:
                candidate["method"] = "aligned_ocr_columns"
            candidate["bbox"][0] = round(candidate["bbox"][0] + start, 2)
            candidate["bbox"][2] = round(candidate["bbox"][2] + start, 2)
        candidates.extend(found)
        warnings.extend(notes)
    grouped = defaultdict(list)
    for candidate in candidates:
        grouped[candidate["metric"], candidate["year"]].append(candidate)
    unique = []
    for (metric, year), group in grouped.items():
        if metric=='inventory':
            parents=[c for c in group if c.get('row_role')=='section']
            if parents and all(c.get('row_role') in {'section','detail'} for c in group):group=parents
        if len({(c["value"], c["unit"], c["currency"]) for c in group}) > 1:
            warnings.append(f"Có nhiều dòng {METRICS[metric]} năm {year} khác giá trị; cần nhập thủ công để tránh chọn nhầm dòng tổng và dòng chi tiết.")
        else:
            unique.append(group[0])
    if not unique:
        warnings.append("Chưa xác định chắc chắn dòng chỉ tiêu, cột năm và đơn vị trên trang này. Bạn vẫn có thể đối chiếu và nhập thủ công.")
    return {"candidates": unique[:80], "warnings": list(dict.fromkeys(warnings)), "notice": NOTICE}


def extract_region(words, width, page_height, document_id, page_number, context):
    if not words:
        return [], []
    height = statistics.median(w[3] - w[1] for w in words)
    rows = rows_from_words(words)
    headers = []
    for row in rows:
        columns = [w for w in row["words"] if w[0] > width * 0.35 and re.fullmatch(r"(?:19|20)\d{2}", w[4])]
        basis = "explicit_year"
        if not columns:
            columns, basis = period_columns(row, rows, context, height)
        units = currency_unit(rows, row, height) if columns else None
        unit_source=None
        if columns and not units and context.get('_continuation_unit') and not unit_mentioned(rows,row,height):
            unit_source=context['_continuation_unit']
            units=(unit_source['currency'],unit_source['unit'])
        currency_below = any(clean(w[4]) in {"vnd", "usd", "eur"}
                             and height * 0.25 < (w[1] + w[3]) / 2 - row["y"] < height * 2
                             and any(abs(w[2] - c[2]) < height for c in columns) for w in words) if columns else False
        left_words = [w[4] for w in row["words"] if columns and w[2] < columns[0][0] and w[0] > width * 0.2]
        bare_year_row = len(columns)>=2 and set(clean(' '.join(left_words)).split()) <= {'year','nam','chi','tieu','code','codes','note','notes','item','items','assets','resources'}
        if columns and units and (currency_below or bare_year_row or basis == "document_fiscal_period") and len({w[4] for w in columns}) == len(columns):
            boundaries=[w[0] for w in row['words'] if clean(w[4]) in {'code','codes','note','notes'} and width*.3<w[0]<columns[0][0]]
            headers.append({**row, "columns": columns, "context": units, "year_basis": basis,
                            'label_end':min(boundaries) if boundaries else width})
            headers[-1]['unit_source']=unit_source
    grouping = number_format(words)
    candidates, warnings = [], []
    for row_index, row in enumerate(rows):
        possible = [h for h in headers if h["y"] + height * 0.7 < row["y"]]
        if not possible:
            continue
        header = possible[-1]
        currency, unit = header["context"]
        cells = []
        for column in header["columns"]:
            aligned = [w for w in row["words"] if abs(w[2] - column[2]) <= max(5, height * 0.7)]
            if len(aligned) == 1:
                value = parse_amount(aligned[0][4], grouping)
                if value is not None:
                    cells.append((column, aligned[0], value))
        if not cells:
            continue
        start = width * 0.2 if width > page_height * 1.2 else 0
        left = min(cell[1][0] for cell in cells)
        label_end=left-height*.2
        def is_note(w):
            return w[0]>=header['label_end']-height*.2 and bool(re.fullmatch(r'(?:[IVX]+\.)?\d+(?:\.\d+)*[a-z]?',w[4],re.I))
        labels = [w for w in row["words"] if start <= w[0] and w[2] < label_end and not re.fullmatch(r"\d+|\d+\([a-z]\)", w[4]) and not is_note(w)]
        label = " ".join(w[4] for w in labels)
        metric = identify_metric(label)
        # Some reports wrap the row label while keeping amounts on its first
        # or last line. Only join adjacent label-only lines in this table.
        if not metric:
            parts={0:list(labels)}
            for direction in (1,-1):
                previous_y=row['y']
                for step in (1,2):
                    adjacent=row_index+direction*step
                    if not 0<=adjacent<len(rows):break
                    other=rows[adjacent]
                    if abs(other['y']-previous_y)>height*1.6 or other['y']<=header['y']+height:break
                    if clean(' '.join(w[4] for w in other['words'])) in {'in which','including','trong do'}:break
                    if any(abs(w[2]-c[2])<=max(5,height*.7) for w in other['words'] for c in header['columns']):break
                    parts[direction*step]=[w for w in other['words'] if start<=w[0] and w[2]<label_end and not re.fullmatch(r'\d+',w[4]) and not is_note(w)]
                    previous_y=other['y']
            # Read both halves of a wrapped label before accepting it. A suffix
            # such as OWNERS' EQUITY must not relabel TOTAL LIABILITIES AND ...
            extended=[w for key in sorted(parts) for w in parts[key]]
            combined=re.sub(r'(?<=\w)-\s+(?=\w)','', ' '.join(w[4] for w in extended))
            metric=identify_metric(combined)
            if metric:labels,label=extended,combined
        if not metric:
            continue
        for column, word, value in cells:
            candidates.append({"document_id": document_id, "page": page_number, "metric": metric,
                               "label": METRICS[metric], "source_label": label, "year": int(column[4]),
                               "value": value, "raw_value": word[4], "unit": unit, "currency": currency,
                               "verified": False, "method": "aligned_pdf_columns",
                               'row_role':'section' if re.match(r'^\s*[IVX]+\.',label) else 'detail' if re.match(r'^\s*\d+\.',label) else None,
                               "year_basis": header["year_basis"],
                               "row_excerpt": label + " | " + " | ".join(cell[1][4] for cell in cells),
                               "bbox": [round(min(w[0] for w in labels), 2), round(min(w[1] for w in labels + [word]), 2), round(word[2], 2), round(max(w[3] for w in labels + [word]), 2)]})
            if header['unit_source']:
                candidates[-1]['unit_source_page']=header['unit_source']['page']
                candidates[-1]['unit_basis']='previous_statement_page'
    return candidates, warnings


def statement_heading(page):
    text=clean(page.get_text(clip=pymupdf.Rect(0,0,page.rect.width,page.rect.height*.25)))
    kinds={kind for kind,pattern in [('balance',r'\bbalance sheet\b'),('income',r'\b(?:income statement|statement of income)\b'),('cashflow',r'\b(?:cash flow statement|statement of cash flows)\b')] if re.search(pattern,text)}
    return (next(iter(kinds)) if len(kinds)==1 else None), bool(re.search(r'\b(?:continued|cont)\b',text))


def continuation_unit(pdf, index, document_id, context, ocr_dir):
    """Read a unit only from nearby pages explicitly continuing the same table."""
    current=pdf[index]
    kind,continued=statement_heading(current)
    if not continued or not kind or current.rect.width>current.rect.height*1.2:return None
    year=context.get('report_year')
    if type(year) is not int:return None
    for prior in range(index-1,max(-1,index-5),-1):
        if context.get('allowed_pages') is not None and prior+1 not in context['allowed_pages']:return None
        previous=pdf[prior]
        if statement_heading(previous)[0]!=kind:return None
        result=extract_page(previous,document_id,prior+1,context=context,ocr_dir=ocr_dir)
        units={(c['currency'],c['unit']) for c in result['candidates']}
        years={c['year'] for c in result['candidates']}
        if len(units)==1 and years=={year,year-1}:
            currency,unit=next(iter(units))
            return {'currency':currency,'unit':unit,'page':prior+1}
        # Do not pass over an unsupported explicit declaration to an older one.
        rows=rows_from_words(previous.get_text('words'))
        if units or any(unit_mentioned(rows,r,12) for r in rows if r['y']<previous.rect.height*.25):return None
    return None


def suggest_page(path, document_id, page_number, *, context=None, ocr_dir=None):
    try:
        with pymupdf.open(path) as pdf:
            if not 1 <= page_number <= len(pdf):
                raise ValueError("Không tìm thấy trang nguồn.")
            result=extract_page(pdf[page_number-1],document_id,page_number,context=context,ocr_dir=ocr_dir)
            if result['candidates'] or not context:return result
            source=continuation_unit(pdf,page_number-1,document_id,context,ocr_dir)
            if source:
                inherited=extract_page(pdf[page_number-1],document_id,page_number,context={**context,'_continuation_unit':source},ocr_dir=ocr_dir)
                if all(c['year'] in {context['report_year'],context['report_year']-1} for c in inherited['candidates']):result=inherited
                if any(c.get('unit_source_page')==source['page'] for c in result['candidates']):
                    result['warnings'].append(f"Đơn vị {UNIT_LABELS[source['unit']]} {source['currency']} lấy từ trang {source['page']} của cùng bảng tiếp nối. Hãy đối chiếu cả trang ghi đơn vị trước khi xác nhận.")
            return result
    except (pymupdf.FileDataError, RuntimeError) as exc:
        raise ValueError("Không đọc được PDF để đề xuất số liệu. Hãy mở tệp gốc để kiểm tra.") from exc
