CONCEPTS = []
for _row in _CATALOG.strip().splitlines():
    _key, _vi, _en, _kind = _row.split("|")
    CONCEPTS.append({"key": _key, "vi": _vi.split(";"), "labels": _en.split(";"), "kind": _kind})


@lru_cache(maxsize=12000)
def clean(text):
    return " ".join(tokens(text))


def contains(text, phrase):
    return f" {phrase} " in f" {text} "


def profile(query):
    q = clean(canonical_query(query))
    causal_text = q.replace("theo yeu to", "")
    if any(contains(causal_text, phrase) for phrase in ("vi sao", "tai sao", "nguyen nhan", "giai thich", "nho dau", "yeu to", "dong luc", "why", "reason", "explain", "drivers")):
        return []
    matches = []
    for concept in CONCEPTS:
        phrases = concept["vi"] + concept["labels"]
        spans = [(m.start(), m.end(), concept) for phrase in phrases for m in re.finditer(r"(?<!\w)" + re.escape(phrase) + r"(?!\w)", q)]
        matches.extend(spans)
    chosen, occupied = [], []
    for start, end, concept in sorted(matches, key=lambda item: (-(item[1] - item[0]), item[0])):
        if any(start < b and end > a for a, b in occupied):
            continue
        if concept["key"] not in {c["key"] for c in chosen}:
            chosen.append(dict(concept))
        occupied.append((start, end))
    # Negation is meaningful for cash versus cash equivalents.
    if "khong gom tuong duong tien" in q:
        chosen = [c for c in chosen if c["key"] != "cash_eq"]
    explicit_notes = "thuyet minh" in q or "notes to" in q
    explicit_kinds = set()
    if "bang can doi" in q or "balance sheet" in q: explicit_kinds.add("balance")
    if "ket qua kinh doanh" in q or "ket qua hoat dong kinh doanh" in q or "income statement" in q: explicit_kinds.add("income")
    if "luu chuyen tien te" in q or "cash flow statement" in q: explicit_kinds.add("cashflow")
    for c in chosen:
        if explicit_notes: c["kind"] = "notes"
        elif len(explicit_kinds) == 1: c["kind"] = next(iter(explicit_kinds))
    return chosen


def expansion(query):
    return " ".join(label for concept in profile(query) for label in concept["labels"])


def statement_kinds(text):
    # A footer referring to notes must not override the statement's own title.
    for line in text[:1500].splitlines():
        title = re.sub(r"^[^\w]+", "", line).strip()
        for kind, pattern in (
            ("notes", r"notes to (?:the )?(?:consolidated )?financial statements|thuyết minh báo cáo"),
            ("balance", r"(?:consolidated )?(?:balance sheet|statement of financial position)|bảng cân đối"),
            ("income", r"(?:consolidated )?(?:income statement|statement of income|statement of profit)|báo cáo kết quả"),
            ("cashflow", r"(?:consolidated )?(?:cash flow statement|statement of cash flows)|báo cáo lưu chuyển"),
        ):
            if re.match(pattern, title, re.I):
                return {kind}
        # OCR headings can lose Vietnamese accents or syllable spaces.
        joined = re.sub(r'[^a-z]','',normalize(title))
        for kind,prefixes in (
            ('notes',('thuyetminhbaocao',)),
            ('balance',('bangcandoi','baocaotinhhinhtaichinh')),
            ('income',('baocaoketqua',)),
            ('cashflow',('baocaoluuchuyentien',)),
        ):
            if joined.startswith(prefixes):return {kind}
    header = " ".join(text[:1500].split())
    # Repeated side navigation is title case; actual headings are usually uppercase.
    if "NOTES TO THE" in header or "NOTES TO CONSOLIDATED" in header:
        return {"notes"}
    kinds = set()
    for kind, patterns in {
        "balance": ["BALANCE SHEET", "STATEMENT OF FINANCIAL POSITION"],
        "income": ["INCOME STATEMENT", "STATEMENT OF INCOME", "STATEMENT OF PROFIT"],
        "cashflow": ["CASH FLOW STATEMENT", "STATEMENT OF CASH FLOWS"],
    }.items():
        if any(p in header for p in patterns): kinds.add(kind)
    if not kinds:
        normalized = clean(header)
        if "notes" in normalized or "thuyet minh" in normalized: return {"notes"}
        if "bang can doi" in normalized or "balance sheet" in normalized: kinds.add("balance")
        if "ket qua" in normalized or "income statement" in normalized or "statement of income" in normalized: kinds.add("income")
        if "luu chuyen tien te" in normalized or "cash flow statement" in normalized or "statement of cash flows" in normalized: kinds.add("cashflow")
    return kinds


_AMOUNT = re.compile(r"(?<!\w)\(?-?\d{1,3}(?:[,.]\d{3})+(?:[,.]\d+)?\)?(?!\w)")


def _ordered_label(line, label, *, short_row=False):
    """Bounded word insertions from adjacent PDF columns; no answer values."""
    words, wanted = line.split(), label.split()
    if len(wanted) < (2 if short_row else 4):
        return False
    prefix = 1 if short_row and len(wanted)<4 else 3
    for start in range(len(words) - prefix + 1):
        if words[start:start + prefix] != wanted[:prefix]:
            continue
        position, noise = start + prefix, 0
        for word in wanted[prefix:]:
            while position < len(words) and words[position] != word and noise < (12 if short_row else 6):
                position += 1
                noise += 1
            if position == len(words) or words[position] != word:
                break
            position += 1
        else:
            return True
    return False


def label_strength(text, concept):
    # Financial PDFs often insert row codes/amounts into a wrapped label.
    # Match its words without numeric interruptions, retaining numbers only as
    # structural evidence that this is a data row. No expected values are used.
    raw_lines = [line.strip() for line in text.splitlines() if line.strip()]
    windows = list(raw_lines)
    windows.extend(a + " " + b for a, b in zip(raw_lines, raw_lines[1:])
                   if (b[:1].islower() or (b.startswith('(') and len(_AMOUNT.findall(b))>=2)
                       or (len(_AMOUNT.findall(b))>=2 and not re.search('[a-zA-ZÀ-ỹ]',_AMOUNT.sub(' ',b))))
                   and (not _AMOUNT.search(a) or not _AMOUNT.search(b)))
    best = 0.0
    for raw in windows:
        if not re.search(r"\d", raw): continue
        line = " ".join(t for t in clean(_AMOUNT.sub(" ", raw)).split() if not t.isdigit())
        labels=list(dict.fromkeys(concept['labels']+concept['vi']))
        for label in labels:
            intact = contains(line, label)
            # Missing syllable spaces are common in Vietnamese OCR. Only
            # contiguous characters are matched; no fuzzy word substitutions.
            vi_joined = label in concept['vi'] and len(label.replace(' ',''))>=8 and label.replace(' ','') in line.replace(' ','')
            # Short English labels may be separated by OCR noise. Require a
            # row code and two amount columns before allowing bounded gaps.
            structured = len(_AMOUNT.findall(raw))>=2 and bool(re.search(r'\b\d{1,3}\b',_AMOUNT.sub(' ',raw)))
            short_row=structured and label in concept['labels'] and 2<=len(label.split())<4
            if not intact and not vi_joined and not _ordered_label(line, label,short_row=short_row): continue
            joined=line.replace(' ','')
            if concept['key']=='current_assets' and any(s in joined for s in ('taisannganhankhac','taisandaihan')):continue
            if concept['key']=='noncurrent_assets' and any(s in joined for s in ('taisandaihankhac','taisandodangdaihan')):continue
            if concept['key']=='liabilities' and any(s in joined for s in ('nonganhan','nodaihan','nophaitranganhan','nophaitradaihan','vonchusohuu','nguonvon')):continue
            if concept['key']=='equity' and any(s in joined for s in ('nophaitra','tongcongnguonvon')):continue
            if concept['key']=='net_income' and any(s in joined for s in ('cuacongtyme','cuacodong','khongkiemsoat')):continue
            if concept['key']=='net_income' and any(s in joined for s in ('chuaphanphoi','retained','undistributed')):continue
            if concept['key']=='total_assets' and short_row and any(s in line.split() for s in ('current','noncurrent','financial','investments','liabilities','equity','other','term')):continue
            # Avoid a broader/sibling row being mistaken for the requested item.
            if concept["key"] == "cash" and ("equivalent" in line or "flows" in line): continue
            if concept["key"] == "current_assets" and ("non current" in line or "other current" in line): continue
            if concept["key"] == "noncurrent_assets" and any(x in line for x in ("other long term", "other non current", "assets in progress", "assets in process")): continue
            if concept["key"] == "liabilities" and any(x in line for x in ("current liabilities", "term liabilities", "other liabilities", "equity", "resources")): continue
            if concept["key"] == "equity" and any(x in line for x in ("liabilities", "total resources")): continue
            if concept["key"] == "gross_revenue" and ("net revenue" in line or "gross profit" in line): continue
            if concept["key"] == "goods_sales" and ("net revenue" in line or "cost of" in line): continue
            if concept["key"] == "retained" and ("previous years" in line or "current year" in line or "brought forward" in line): continue
            if concept["key"] == "inventory" and ("allowance" in line or "provision" in line or "change in" in line): continue
            before = line.split(label, 1)[0].strip()
            exact = not before or all(re.fullmatch(r"[ivx]+|[a-z]", t) for t in before.split())
            best = max(best, 1.0 + .4 * exact + .02 * min(8, len(label.split()))
                       + .08 * min(2, len(_AMOUNT.findall(raw))) + .12 * contains(clean(raw), label)
                       - (.2 if not intact else 0))
    if not best and any(contains(clean(text), label) for label in concept["labels"]+concept['vi']):
        best = .25
    return best


def rank_rows(query, hits, page_texts, limit=5):
    concepts = profile(query)
    if not concepts: return hits[:limit]
    ranked = []
    for rank, hit in enumerate(hits):
        kinds = statement_kinds(hit["text"])
        if not kinds: kinds = statement_kinds(page_texts.get((hit["document_id"], hit["page"]), ""))
        strengths = {}
        for c in concepts:
            strength = label_strength(hit["text"], c)
            if strength:
                strengths[c["key"]] = strength * (3 if c["kind"] in kinds else .6 if kinds else 1)
        quality = max(strengths.values(), default=0)
        score = quality + .12 / (1 + rank)
        ranked.append({"hit": hit, "strengths": strengths, "score": score})
    selected, covered, page_counts, seen = [], {}, {}, set()
    while ranked and len(selected) < limit:
        def priority(row):
            gain = sum(max(0, v - covered.get(key, 0)) for key, v in row["strengths"].items())
            return gain + row["score"]
        ranked.sort(key=priority, reverse=True)
        row = ranked.pop(0); hit = row["hit"]
        page = (hit["document_id"], hit["page"])
        signature = clean(hit["text"])
        improves = any(v >= 3 and v > covered.get(key, 0) + .01 for key, v in row["strengths"].items())
        if signature in seen or (page_counts.get(page, 0) >= 1 and not improves): continue
        selected.append({**hit, "context_rank": 2 if max(row["strengths"].values(), default=0) >= 3 else 1 if row["strengths"] else 0})
        seen.add(signature)
        for key, value in row["strengths"].items():
            if value >= 3:
                covered[key] = max(covered.get(key, 0), value)
        page_counts[page] = page_counts.get(page, 0) + 1
    return selected
